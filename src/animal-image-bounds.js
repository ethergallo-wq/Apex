export function getAnimalImageBounds(src) {
  if (!src) return null;
  const clean = String(src).split('?')[0].split('#')[0];
  const file = clean.split('/').pop();
  const value = ANIMAL_IMAGE_BOUNDS[file];
  if (!value) return null;
  const [naturalWidth, naturalHeight, x, y, width, height] = value;
  return { naturalWidth, naturalHeight, x, y, width, height };
}
